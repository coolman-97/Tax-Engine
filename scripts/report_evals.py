#!/usr/bin/env python3
"""Regenerate docs/EVALS.md from a real eval run.

Like docs/VALIDATION.md, this is generated rather than written, so the numbers
in it cannot drift from the pipeline. It runs from committed cassettes by
default, so it needs no key.
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "packages" / "pipeline"))
sys.path.insert(0, str(ROOT / "packages" / "engine"))

from taxpipeline.corpus import build_corpus  # noqa: E402
from taxpipeline.evals.run import TARGET_PRECISION, run  # noqa: E402
from taxpipeline.extract import EVIDENCE_MODEL, STRUCTURE_MODEL  # noqa: E402

OUT = ROOT / "docs" / "EVALS.md"


def main() -> int:
    live = "--live" in sys.argv
    r = run(live=live, record=live)
    docs = build_corpus()

    fields = []
    for name, s in r["fields"].items():
        p = f"{s['precision']:.3f}" if s["precision"] is not None else "—"
        rec = f"{s['recall']:.3f}" if s["recall"] is not None else "—"
        fields.append(
            f"| `{name}` | {s['weight']} | {s['n']} | {p} | {rec} | "
            f"{s['wrong']} | {s['missed']} | {s['why']} |")

    calib = [
        f"| {row['range']} | {row['n']} | {row['mean_confidence']:.3f} | "
        f"{row['accuracy']:.3f} | {row['gap']:+.3f} |"
        for row in r["calibration"]
    ]
    ops = [
        f"| {o['threshold']:.2f} | {o['auto_accepted']} | "
        f"{format(o['precision'], '.3f') if o['precision'] is not None else '—'} | "
        f"{o['review_share']:.0%} |"
        for o in r["operating_points"]
    ]
    corpus = [
        f"| `{d.id}` | {d.kind} | {d.tax_year} | {len(d.truth)} | "
        f"{d.char_count():,} | {d.note or '—'} |"
        for d in docs
    ]

    per_doc_cost = r["cost_usd"] / max(1, r["documents"])

    doc = f"""# Extraction evals

Generated by `make eval` (`scripts/report_evals.py`). The numbers below come
from an actual run, against committed cassettes recorded from the API — so this
document cannot drift from the pipeline, and a reviewer can reproduce it with
no key and no network.

- Evidence pass: **`{EVIDENCE_MODEL}`** · structure pass: **`{STRUCTURE_MODEL}`**
- {r['documents']} documents, {r['pages']} pages, **{r['evidence_spans']} cited
  evidence spans**, {r['judgements']} scored field judgements
- {r['input_tokens']:,} input / {r['output_tokens']:,} output tokens ·
  **${r['cost_usd']:.4f}** total, ${per_doc_cost:.4f} per document

Token counts and cost come from the recorded responses, so they are the real
figures from the live run. Wall-clock latency is deliberately **not** reported
here: replaying a cassette measures reading a JSON file, not the API, so a
number in this document would be both meaningless and different on every
machine — which is exactly what made this report non-deterministic and the CI
gate flaky the first time round. `make eval-live` prints per-document latency
from an actual API run.

---

## Why it is scored this way

**Per field, not per document.** A document-level accuracy figure hides that
the fields differ wildly in consequence. `date_placed_in_service` sets the whole
depreciation schedule and therefore the exit tax; `insurance` moves cash flow
slightly. They are weighted ×4 / ×2 / ×1 / ×0.5.

**Precision separated from recall.** They are not interchangeable here. A
missing field routes to a human and costs minutes. A *wrong* field flows
silently into a recommendation an advisor defends with their license. The
pipeline is tuned for precision.

**Calibration, not just accuracy.** The auto-accept threshold in
`provenance.py` gates on confidence. If confidence does not mean what it says,
that gate is decoration.

## Per-field results

| field | weight | n | precision | recall | wrong | missed | why it is weighted this way |
|---|---|---|---|---|---|---|---|
{chr(10).join(fields)}

**Weighted recall (critical fields ×4): {r['weighted_recall']:.3f}**

## Calibration

| confidence | n | mean confidence | accuracy | gap |
|---|---|---|---|---|
{chr(10).join(calib)}

**Expected calibration error: {r['ece']:.3f}.** The gap column is positive
throughout, which means the pipeline is *under*-confident: it is right more
often than it claims to be. That is the safe direction — an over-confident
extractor auto-accepts wrong values — but it is not free, because it routes
fields to human review that did not need it. The confidence prior in
`extract.py` is a heuristic over the cited span, and this table is the evidence
for how much to trust it.

## Operating points

The auto-accept threshold is **chosen from this curve**, not picked. Target:
field-level precision at or above {TARGET_PRECISION:.0%}.

| threshold | auto-accepted | precision | routed to review |
|---|---|---|---|
{chr(10).join(ops)}

## The corpus

Generated rather than hand-labelled, which makes ground truth exact by
construction and — more importantly — lets the mess be **deliberate**.

| document | kind | year | properties | chars | note |
|---|---|---|---|---|---|
{chr(10).join(corpus)}

What is deliberately wrong with it:

- **2023 is missing.** Clients lose returns. Reconciliation has to report the
  gap rather than interpolate across it.
- **One property is named three ways** across years — `1247 Ocean Blvd`,
  `1247 Ocean Boulevard`, `1247 Ocean Blv.` — so entity resolution is actually
  exercised.
- **Depreciation disagrees between 2022 and 2024** ($28,509 vs $32,582),
  because the preparer changed the land allocation and wrote that down nowhere.
  This is the case that blocks a recommendation in the demo, and it arrives
  through the pipeline rather than being hand-authored.
- **The 2021 return is a degraded scan**, with character *and digit* level OCR
  corruption, and its ground truth stays the true value. There is therefore no
  reading of a corrupted figure that scores as correct. What this document
  really measures is whether the model knows it cannot read something.

## What the degraded scan showed

On the 2021 scan, `18,615` of mortgage interest was corrupted to `l8,615` — a
lowercase L for a 1, a classic scanner confusion. The pipeline extracted
**18,615**, correctly, by using the form's internal arithmetic to resolve the
ambiguous glyph, which is what the evidence prompt asks it to do.

That is the behaviour worth having: not that it guessed well, but that it had a
consistency check available and used it.

## Where this eval is weak

Stated because an eval that only reports wins is marketing, and because a
perfect score is a warning sign, not a victory.

- **Every field scores 1.000, so this eval currently has little discriminating
  power.** It can tell a working pipeline from a broken one. It cannot tell a
  good pipeline from a better one, and it would not detect a small regression.
- **n is small.** {r['judgements']} judgements across {r['documents']} documents
  is enough to catch a systematic failure and nowhere near enough to measure a
  1% precision difference.
- **The corpus is synthetic and I wrote both sides.** The documents are
  rendered from the same figures the ground truth carries, so the pipeline is
  not being tested against handwriting, scan skew, unusual preparer layouts,
  multi-page returns with continuation sheets, or K-1s. Real returns are worse
  than this in ways I did not think to simulate — which is the fundamental
  limitation of any generated corpus.
- **The operating-point curve is degenerate at this accuracy.** With no errors
  at any confidence level, the threshold it recommends is 0.00. The threshold
  actually shipped in `provenance.py` is 0.90, chosen conservatively rather
  than read off this curve, and the curve should be re-derived on a corpus that
  produces real errors.

**What I would do about it**, in order: many more generated documents with
harder degradation and layout variation; a held-out split so prompt changes
cannot be tuned against the test set; a small set of *real* returns, redacted,
as the honest benchmark; and per-document rather than per-corpus reporting so a
single bad document cannot hide in an average.
"""
    OUT.write_text(doc)
    print(f"wrote {OUT.relative_to(ROOT)}")
    print(f"  {r['judgements']} judgements · weighted recall "
          f"{r['weighted_recall']:.3f} · ECE {r['ece']:.3f} · ${r['cost_usd']:.4f}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
